export interface ShipClass {
  id: string;
  name: string;
  model: ModelId;
  radius: number;
  hull: number;
  shields: number;
  shieldRegen: number; // per second
  shieldDelay: number; // seconds after a hit before regen
  maxSpeed: number;
  boostSpeed: number;
  strafeSpeed: number;
  accel: number; // velocity response (1/s)
  pitchRate: number; // rad/s
  yawRate: number;
  rollRate: number;
  turnResponse: number;
  energy: number;
  energyRegen: number;
  boostDrain: number;
  gun: GunSpec;
  missiles: number;
  /** Missile type; AI ships use DEFAULT_MISSILE with slower motors. */
  missile?: MissileSpec;
  /** Player ships: weapon slots (each takes a gun or, if the ship carries missiles, a launcher). */
  weaponSlots?: number;
  /** What a newly bought hull comes with. */
  defaultWeapons?: string[];
  /** Fitted guns, one per gun slot (set by the loadout, player ships only). */
  mounts?: GunSpec[];
  /** Fitted missile launchers (set by the loadout). */
  launchers?: MissileSpec[];
  price: number;
  /** Equipment slots (player ships). */
  equipSlots?: number;
  /** Shop blurb. */
  description?: string;
  /** Credits paid for destroying one. */
  bounty?: number;
  /** Compound collision for long hulls: local [x, y, z, radius] spheres. */
  hitSpheres?: [number, number, number, number][];
  /** Civilian traffic: never targeted, never shoots. */
  civilian?: boolean;
  /** A civilian the player can still lock on to (mission targets). */
  targetable?: boolean;
  /** Fixed installation: never moves (turrets, relays, modules). */
  anchored?: boolean;
  /** A part of a capital ship (engine, hangar, bridge): the player's to shoot, the AI ignores it. */
  subsystem?: boolean;
  /** Player ships: whose yard builds it. Independent ('kestrel') yards sell to anyone; a
   *  faction's yards sell only to pilots working for that faction. */
  maker?: FactionId;
  /** False for hulls nobody sells (police). */
  forSale?: boolean;
  /** Shop notes: what the hull is good and bad at. */
  strengths?: string;
  weaknesses?: string;
}

